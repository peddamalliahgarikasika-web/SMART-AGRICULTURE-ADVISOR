def get_text(lang, key):
    """Look up `key` in `lang`'s dictionary, falling back to English,
    and finally to the key itself if it exists nowhere (so the UI
    never shows a raw Jinja error, just a readable placeholder)."""
    lang_dict = LANGUAGES.get(lang, LANGUAGES[DEFAULT_LANGUAGE])
    if key in lang_dict:
        return lang_dict[key]
    return LANGUAGES[DEFAULT_LANGUAGE].get(key, key)
