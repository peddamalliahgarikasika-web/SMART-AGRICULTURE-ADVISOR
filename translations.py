# =====================================================
# translations.py
# -----------------------------------------------------
# Lightweight multi-language (i18n) support for
# Smart Agriculture Advisor.
#
# No external i18n library is required. Every UI string
# used across the templates is looked up by a short key
# in the LANGUAGES dictionary below. If a key is missing
# for the currently selected language, it automatically
# falls back to English so the site never shows a blank
# or broken label while new languages are being expanded.
#
# Supported languages:
#   en - English
#   hi - Hindi
#   te - Telugu
#   ta - Tamil
#   kn - Kannada
#   ml - Malayalam
#   mr - Marathi
#   gu - Gujarati
#   bn - Bengali
#   pa - Punjabi
#   or - Odia
#
# COVERAGE NOTE: en, hi and te have full coverage of every
# key used across the site (nav, chatbot, crop form, disease
# form, results tables, state/crop/soil option lists, theme
# toggle). The remaining languages have the nav/chat basics;
# any key they're missing automatically falls back to English
# (see get_text() below) rather than showing a blank label.
# Contribute more translations by extending LANGUAGES[<code>].
#
# HOW TO ADD MORE STRINGS:
#   1. Add the key with its English text under LANGUAGES["en"].
#   2. Add the same key with translated text under any other
#      language block you want to support. If you skip a
#      language, English is shown automatically for that key.
#
# HOW TO ADD A NEW LANGUAGE:
#   1. Add "<code>": "<Native name>" to LANGUAGE_NAMES.
#   2. Add a new "<code>": { ... } block to LANGUAGES with as
#      many keys translated as you like (missing keys fall
#      back to English automatically).
# =====================================================

